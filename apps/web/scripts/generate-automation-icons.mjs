import { mkdir, writeFile } from 'node:fs/promises';
import { Buffer } from 'node:buffer';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { GitMergeIcon } from '@primer/octicons-react';
import {
  ChartColumnIncreasing,
  BatteryWarning,
  GitCommitVertical,
  GitMergeConflict,
  Lightbulb,
  Megaphone,
  SquarePen,
  TriangleAlert,
  Wrench,
  Zap,
} from 'lucide-react';
import sharp from 'sharp';
import { siDependabot, siGithub, siSentry } from 'simple-icons';

const outputDirectory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../public/automation-icons',
);

const lucideIcons = {
  'battery-warning': BatteryWarning,
  'chart-column-increasing': ChartColumnIncreasing,
  'git-commit-vertical': GitCommitVertical,
  'git-merge-conflict': GitMergeConflict,
  lightbulb: Lightbulb,
  megaphone: Megaphone,
  'square-pen': SquarePen,
  'triangle-alert': TriangleAlert,
  wrench: Wrench,
  zap: Zap,
};

const octicons = {
  'git-merge': GitMergeIcon,
};

const simpleIcons = {
  dependabot: siDependabot,
  github: siGithub,
  sentry: siSentry,
};

function wrapIcon(content) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96"><rect width="96" height="96" rx="12" fill="white"/><g transform="translate(20 20)">${content}</g></svg>`;
}

function renderLucideIcon(Icon) {
  return wrapIcon(
    renderToStaticMarkup(
      createElement(Icon, {
        width: 56,
        height: 56,
        color: '#000000',
        strokeWidth: 2,
      }),
    ),
  );
}

function renderOcticon(Icon) {
  return wrapIcon(
    renderToStaticMarkup(
      createElement(Icon, {
        size: 56,
        fill: '#000000',
      }),
    ),
  );
}

function renderSimpleIcon(icon) {
  return wrapIcon(
    `<svg width="56" height="56" viewBox="0 0 24 24" fill="#000000" aria-hidden="true"><path d="${icon.path}"/></svg>`,
  );
}

await mkdir(outputDirectory, { recursive: true });

for (const [name, Icon] of Object.entries(lucideIcons)) {
  await sharp(Buffer.from(renderLucideIcon(Icon)))
    .png()
    .toFile(path.join(outputDirectory, `${name}.png`));
}

for (const [name, Icon] of Object.entries(octicons)) {
  await sharp(Buffer.from(renderOcticon(Icon)))
    .png()
    .toFile(path.join(outputDirectory, `${name}.png`));
}

for (const [name, icon] of Object.entries(simpleIcons)) {
  await sharp(Buffer.from(renderSimpleIcon(icon)))
    .png()
    .toFile(path.join(outputDirectory, `${name}.png`));
}

await writeFile(
  path.join(outputDirectory, 'README.md'),
  'Generated by `pnpm --filter @roomote/web automation:icons`. Do not edit these PNGs directly.\n',
);
