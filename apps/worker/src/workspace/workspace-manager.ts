  public async configure(options?: {
    gitAuthorName?: string;
    gitAuthorEmail?: string;
  }): Promise<void> {
    // Write the file-backed credential helper so git always reads the
    // freshest token, even after the periodic refresh replaces the file.
    const credentialHelperPath = ensureGitCredentialHelper();

    const gitEmail = shellEscape(
      options?.gitAuthorEmail || 'roomote@roomote.dev',
    );
    const gitName = shellEscape(options?.gitAuthorName || PRODUCT_NAME);

    const executor = new CommandExecutor(
      this.workspaceRoot,
      this.env,
      this.verbose,
    );

    await executor.executeAll([
      {
        name: 'GitHub auth setup-git',
        run: 'if [ -n "${GH_TOKEN:-}" ]; then gh auth setup-git; else echo "Skipping gh auth setup-git because GH_TOKEN is not set"; fi',
        timeout: 60,
        continue_on_error: false,
      },
      {
        // Override provider credential helpers with a file-backed helper that
        // reads the latest token from disk for each git operation.
        name: 'GitHub credential helper (file-backed)',
        run: `git config --global --replace-all credential.https://github.com.helper '!${credentialHelperPath}'`,
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'GitLab credential helper (file-backed)',
        run: `git config --global --replace-all credential.https://gitlab.com.helper '!${credentialHelperPath}'`,
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'GitLab credential useHttpPath',
        run: 'git config --global credential.https://gitlab.com.useHttpPath true',
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'Source-control credential helper (file-backed)',
        run: `git config --global --replace-all credential.helper '!${credentialHelperPath}'`,
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'Source-control credential useHttpPath',
        run: 'git config --global credential.useHttpPath true',
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'Source-control auth include file',
        run: `git config --global --get-all include.path | grep -Fx -- '${shellEscape(
          SOURCE_CONTROL_GIT_CONFIG_PATH,
        )}' >/dev/null || git config --global --add include.path '${shellEscape(
          SOURCE_CONTROL_GIT_CONFIG_PATH,
        )}'`,
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'Git config email',
        run: `git config --global user.email '${gitEmail}'`,
        timeout: 60,
        continue_on_error: false,
      },
      {
        name: 'Git config name',
        run: `git config --global user.name '${gitName}'`,
        timeout: 60,
        continue_on_error: false,
      },
    ]);
  }

  /**
   * Install tool versions using mise.
   *
   * Workspace-level tool versions continue to use a shared `.tool-versions`
   * file at the workspace root. Repository-level tool versions are treated as
   * fallback entries: any checked-in repo `.tool-versions` wins first, and
   * missing tools from the environment config are written into a generated
   * `mise.local.toml` so they can fill gaps without replacing repo-owned pins.
   */
  private async installToolVersions(
    targetPath: string,
    toolVersionsConfig?: Record<string, string>,
    options?: {
      excludeFromGit?: boolean;
    },
  ): Promise<void> {
    const toolVersionsPath = join(targetPath, '.tool-versions');
    const repoToolVersions = existsSync(toolVersionsPath)
      ? parseToolVersionsFile(await readFile(toolVersionsPath, 'utf-8'))
      : {};
    const repoFallbackConfig = toolVersionsConfig
      ? Object.fromEntries(
          Object.entries(toolVersionsConfig).filter(
            ([tool]) => repoToolVersions[tool] === undefined,
          ),
        )
      : undefined;
    const hasGeneratedRepoFallback = await this.syncGeneratedRepoMiseConfig(
      targetPath,
      repoFallbackConfig,
      options,
    );
    const hasRepoMiseConfig = REPO_MISE_CONFIG_FILENAMES.some((filename) =>
      existsSync(join(targetPath, filename)),
    );

    if (!hasRepoMiseConfig && !hasGeneratedRepoFallback) {
      return;
    }

    console.log(`Installing tools from repo-local mise config`);

    const executor = new CommandExecutor(targetPath, this.env, this.verbose);

    await executor.execute({
      name: 'Install tool versions',
      run: 'mise install',
      timeout: 300,
      continue_on_error: true,
    });

    const listResult = await executor.execute({
      name: 'Listing installed tools',
      run: 'mise ls --json',
      timeout: 30,
      continue_on_error: true,
    });

    if (listResult.success && listResult.stdout) {
      try {
        const tools: Record<string, { version: string; active: boolean }[]> =
          JSON.parse(listResult.stdout);

        const toolVersions = Object.entries(tools).flatMap(([name, versions]) =>
          versions.filter((v) => v.active).map((v) => `${name}@${v.version}`),
        );

        if (toolVersions.length > 0) {
          console.log(toolVersions.join(', '));
        }
      } catch {
        // Ignore errors.
      }
    }
  }

