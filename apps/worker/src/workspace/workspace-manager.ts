/**
 * Escape a string for safe use inside single-quoted shell arguments.
 * Replaces each `'` with `'\''` (end quote, escaped quote, re-open quote).
 */
function shellEscape(value: string): string {
  return value.replace(/'/g, "'\\''");
}

function parseOriginHeadLsRemote(stdout?: string): string | null {
  if (!stdout) {
    return null;
  }

  for (const line of stdout.split('\n')) {
    const match = line.match(/^ref:\s+refs\/heads\/([^\s]+)\s+HEAD$/);
    if (match?.[1]) {
      return match[1];
    }
  }

  return null;
}

function parseLocalOriginHead(stdout?: string): string | null {
  const ref = stdout?.trim();

  if (!ref?.startsWith('origin/')) {
    return null;
  }

  return ref.slice('origin/'.length) || null;
}

function renderToolVersionsFile(
  toolVersionsConfig: Record<string, string>,
): string {
  return Object.entries(toolVersionsConfig)
    .map(([tool, version]) => `${tool} ${version}`)
    .join('\n')
    .concat('\n');
}

function parseToolVersionsFile(content: string): Record<string, string> {
  return Object.fromEntries(
    content
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line.length > 0 && !line.startsWith('#'))
      .map((line) => {
        const [tool, ...versionParts] = line.split(/\s+/);
        return [tool, versionParts.join(' ')];
      })
      .filter(([tool, version]) => Boolean(tool) && Boolean(version)),
  );
}

function renderGeneratedRepoMiseConfig(
  toolVersionsConfig: Record<string, string>,
): string {
  const toolsBlock = Object.entries(toolVersionsConfig)
    .map(([tool, version]) => `${tool} = ${JSON.stringify(version)}`)
    .join('\n');

  return `${GENERATED_REPO_MISE_CONFIG_HEADER}\n[tools]\n${toolsBlock}\n`;
}

