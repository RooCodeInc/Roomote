/**
 * invites
 *
 * Deployment invite links. Possession of the raw token (only its hash is
 * stored) authorizes sign-up through any auth method, including
 * email/password. The first admin is authorized by the SETUP_TOKEN env value
 * acting as a system invite rather than a row here.
 */

export const invites = pgTable(
  'invites',
  {
    id: uuid('id').notNull().primaryKey().defaultRandom(),
    tokenHash: text('token_hash').notNull(),
    label: text('label'),
    invitedByUserId: text('invited_by_user_id').references(() => users.id, {
      onDelete: 'set null',
    }),
    // Role granted to users admitted through this invite. The first user of
    // a deployment is always an admin regardless of this value.
    role: text('role').notNull().default('member').$type<UserRole>(),
    maxUses: integer('max_uses').notNull().default(1),
    usedCount: integer('used_count').notNull().default(0),
    expiresAt: timestamp('expires_at'),
    revokedAt: timestamp('revoked_at'),
    createdAt: timestamp('created_at').notNull().defaultNow(),
    updatedAt: timestamp('updated_at').notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex('invites_token_hash_unique').on(table.tokenHash),
    index('invites_created_at_idx').on(table.createdAt),
  ],
);

